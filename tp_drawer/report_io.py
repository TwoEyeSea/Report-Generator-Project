"""Builds a full geotechnical report .docx from a Project's data.

The report is generated by rendering data/report_template.docx (a copy of
a real reference report with its project-specific text replaced by
docxtpl/Jinja2 tags -- see scripts/build_report_template.py for how that
template was produced) against a "render context": a plain dict of the
values its tags reference.

This module only builds that context and drives docxtpl -- it doesn't
know anything about .xlsx files (that's excel_io.py) or about how a
Project's data got hydrated with catalog descriptions (that's catalog.py's
hydrate_descriptions, which the caller is expected to have already run,
same as drawing.py assumes).

WHAT'S DATA-DRIVEN VS. STILL BOILERPLATE:
Most of the report -- the header/intro facts, the trial pit results table,
and the per-stratum soil descriptions -- comes straight from the Project.
Two sections lean on small catalogs (formation commentary and foundation
write-ups, both in catalog.py) that grow the same way the unit catalog
does: an unrecognised formation or foundation name just produces a clearly
marked placeholder instead of failing, so the report can still be
generated and finished by hand -- and the next project that uses the same
formation/foundation gets it for free.
"""

import datetime
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from docxtpl import DocxTemplate

from tp_drawer.catalog import FormationTemplate, FoundationOption, find_formation, find_foundation_option
from tp_drawer.models import DEFAULT_TERMINATION_REASON, Project, TrialPit
from tp_drawer.units import format_feet_inches

DEFAULT_REPORT_TEMPLATE_PATH = Path(__file__).resolve().parent.parent / "data" / "report_template.docx"

_NUMBER_WORDS = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven", 8: "Eight", 9: "Nine", 10: "Ten"}


def _number_word(n: int) -> str:
    """Spell out small pit counts the way the report's prose does ("Two
    (2 No.) trial pits"); falls back to the digit itself past ten rather
    than guessing at English number words nobody would type by hand."""
    return _NUMBER_WORDS.get(n, str(n))


def _ordinal(day: int) -> str:
    """1 -> "1st", 2 -> "2nd", 3 -> "3rd", 4 -> "4th", ..., 11-13 -> "th"
    (the standard irregular exception -- 11th/12th/13th, not 11st/12nd/13rd)."""
    if 11 <= day % 100 <= 13:
        suffix = "th"
    else:
        suffix = {1: "st", 2: "nd", 3: "rd"}.get(day % 10, "th")
    return f"{day}{suffix}"


def _format_report_date(raw: str, *, with_of: bool) -> str:
    """Reparse the "23-May-2026" text excel_io.py produces and render it
    in the report's own prose style: "23rd May 2026", or with_of=True,
    "23rd of May 2026" (used for the one sentence that reads "...completed
    on the 23rd of May 2026..."). A hand-typed, non-standard date (e.g.
    "TBD") is shown back verbatim rather than raising an error."""
    try:
        dt = datetime.datetime.strptime(raw, "%d-%B-%Y")
    except ValueError:
        return raw
    day = _ordinal(dt.day)
    return f"{day} of {dt.strftime('%B %Y')}" if with_of else f"{day} {dt.strftime('%B %Y')}"


def _format_report_date_numeric(raw: str) -> str:
    """Reparse the "23-May-2026" text excel_io.py produces into the plain
    numeric "DD/MM/YYYY" style the appendix headers use (as opposed to
    the main report's ordinal prose -- see _format_report_date) -- the
    same underlying date, just a different header's own convention. A
    hand-typed, non-standard date is shown back verbatim, same as above."""
    try:
        dt = datetime.datetime.strptime(raw, "%d-%B-%Y")
    except ValueError:
        return raw
    return dt.strftime("%d/%m/%Y")


@dataclass
class PitRow:
    """One row of the report's Trial Pit Results table."""

    number: str
    groundwater: str
    final_depth: str
    stratum: str


def _build_pit_rows(project: Project) -> list[PitRow]:
    rows = []
    for pit in project.pits:
        groundwater = format_feet_inches(pit.groundwater_depth_in) if pit.groundwater_depth_in is not None else "Not Encountered"
        rows.append(
            PitRow(
                number=pit.number,
                groundwater=groundwater,
                # "Final Depth of Pit" is the pit's total excavated depth --
                # computed from its layers rather than re-entered by hand
                # anywhere, so it can never drift out of sync with them.
                final_depth=format_feet_inches(pit.total_depth_in),
                stratum=pit.termination_reason.title(),
            )
        )
    return rows


# The placeholder used in place of a real MADE/NATIVE call when a layer's
# is_native was never set (no matching catalog entry, or the catalog entry
# itself hasn't been marked yet) -- a deliberate, visible prompt to fix it
# rather than a silent guess at a real geotechnical distinction.
_UNKNOWN_NATIVE_PREFIX = "[MADE/NATIVE?]"


@dataclass
class StratumRow:
    """One repeated "Soil Descriptions" block: one row per unique layer
    name found anywhere across the project's pits, in first-encountered
    order. `name` is already the full "{MADE/NATIVE} GROUND, {UNIT NAME}"
    text the template's "Strata: " label is followed by -- not just the
    bare unit name -- so the template itself needs no MADE/NATIVE logic."""

    name: str
    pits_encountered: str
    thickness_range: str
    underlying: str
    description: str


def _pits_encountered_label(pit_numbers: list[str], total_pits: int) -> str:
    if len(pit_numbers) == total_pits:
        return "All Pits"
    if len(pit_numbers) == 1:
        return f"Trial Pit {pit_numbers[0]}"
    return "Trial Pits " + ", ".join(pit_numbers)


def _made_or_native_prefix(is_native: bool | None) -> str:
    if is_native is True:
        return "NATIVE"
    if is_native is False:
        return "MADE"
    return _UNKNOWN_NATIVE_PREFIX


def _build_strata(project: Project) -> list[StratumRow]:
    order: list[str] = []
    seen: set[str] = set()
    for pit in project.pits:
        for layer in pit.layers:
            key = layer.name.strip().lower()
            if key not in seen:
                seen.add(key)
                order.append(layer.name)

    total_pits = len(project.pits)
    rows = []
    for name in order:
        key = name.strip().lower()
        thicknesses = []
        pit_numbers = []
        # Every occurrence of this unit contributes its own overlying unit
        # (or "On grade" if it's the first layer in that pit) -- a unit can
        # genuinely sit under different things in different pits (e.g. one
        # pit skips a layer another pit has), so this collects every
        # distinct case seen, in first-encountered order, rather than just
        # the first pit's answer. "On grade" is checked into the same
        # list/dedup set as any named unit -- not merged with anything --
        # so a unit that's on-grade in one pit and underlies a named unit
        # in another correctly ends up with two separate entries.
        underlying_values: list[str] = []
        seen_underlying: set[str] = set()
        description = ""
        is_native = None
        native_set = False
        for pit in project.pits:
            for i, layer in enumerate(pit.layers):
                if layer.name.strip().lower() != key:
                    continue
                thicknesses.append(layer.thickness_in)
                pit_numbers.append(pit.number)
                this_underlying = pit.layers[i - 1].name if i > 0 else "On grade"
                underlying_key = this_underlying.strip().lower()
                if underlying_key not in seen_underlying:
                    seen_underlying.add(underlying_key)
                    underlying_values.append(this_underlying)
                if not description and layer.description:
                    description = layer.description
                if not native_set:
                    is_native = layer.is_native
                    native_set = True
                break  # a layer name is assumed to appear at most once per pit

        min_t, max_t = min(thicknesses), max(thicknesses)
        thickness_range = format_feet_inches(min_t) if min_t == max_t else f"{format_feet_inches(min_t)} to {format_feet_inches(max_t)}"
        rows.append(
            StratumRow(
                name=f"{_made_or_native_prefix(is_native)} GROUND, {name.upper()}",
                pits_encountered=_pits_encountered_label(pit_numbers, total_pits),
                thickness_range=thickness_range,
                underlying=", ".join(underlying_values),
                description=description,
            )
        )
    return rows


def _primary_termination_reason(project: Project) -> str:
    """The formation the report's DISCUSSION/CONCLUSION sections talk
    about: whichever termination_reason is shared by the most pits, ties
    broken by first-encountered order (Counter.most_common is stable)."""
    reasons = [pit.termination_reason for pit in project.pits if pit.termination_reason]
    if not reasons:
        return DEFAULT_TERMINATION_REASON
    return Counter(reasons).most_common(1)[0][0]


def _pits_matching_reason(project: Project, reason: str) -> list[TrialPit]:
    return [pit for pit in project.pits if pit.termination_reason == reason]


def _formation_commentary(project: Project, primary_reason: str, formation_templates: list[FormationTemplate]) -> str:
    """Fills in whichever formation catalog entry matches `primary_reason`.
    Different named formations word their commentary differently -- e.g.
    "Native Bedrock was not encountered..., consolidated native marl was
    encountered at trial pit No. {pit_number} at {depth}..." (used when the
    stratum was only hit in some pits, at varying depths) vs "Native
    Bedrock was encountered within all the excavations...; depth to be
    approximately between {depth_range}..." (used when every pit hit it).
    Rather than have report_io.py decide which wording style applies, it
    just computes every value any known template might reference and lets
    each catalog entry's own text pick whichever placeholders it needs --
    an unused kwarg is harmless to str.format()."""
    template = find_formation(primary_reason, formation_templates)
    if template is None:
        return (
            f'[No stored commentary for "{primary_reason.title()}" yet -- describe this formation\'s '
            "geological setting and bearing characteristics here, then add it to the formation catalog "
            "so future reports fill it in automatically.]"
        )
    matching_pits = _pits_matching_reason(project, primary_reason)
    shallowest = min(matching_pits, key=lambda pit: pit.total_depth_in)
    depths = [pit.total_depth_in for pit in matching_pits]
    min_depth, max_depth = min(depths), max(depths)
    depth_range = format_feet_inches(min_depth) if min_depth == max_depth else f"{format_feet_inches(min_depth)} to {format_feet_inches(max_depth)}"
    return template.commentary.format(
        pit_number=shallowest.number,
        depth=format_feet_inches(shallowest.total_depth_in),
        depth_range=depth_range,
    )


def _notes_context(project: Project) -> dict:
    """Section 3.1 Notes: a bold heading followed by one or more dash-
    bulleted lines (notes_lines), rendered by a {%p for %} loop in the
    template so it isn't limited to exactly one line.
    - Nothing entered on the form at all -> a default note reassuring the
      reader the pits were excavated successfully, rather than a bare
      "None." that reads as if the field was simply skipped.
    - Every pit's note present and identical -> one combined "All Tps:" line.
    - Anything else (some blank, or notes that differ) -> "Notes:" with one
      bulleted line per pit that actually has one."""
    notes = [(pit.number, pit.extra_note.strip()) for pit in project.pits if pit.extra_note.strip()]
    if not notes:
        return {"notes_heading": "All Tps:", "notes_lines": ["- Excavated successfully"]}
    distinct_texts = {text for _, text in notes}
    if len(distinct_texts) == 1 and len(notes) == len(project.pits):
        return {"notes_heading": "All Tps:", "notes_lines": [f"- {next(iter(distinct_texts))}"]}
    return {"notes_heading": "Notes:", "notes_lines": [f"- TP{number}: {text}" for number, text in notes]}


@dataclass
class FoundationSection:
    """One "5.N" foundation subsection. heading_text already has whichever
    wording applies -- "Recommended Foundation: X" when X is the only
    recommendation, or "Option {n} - X" when there's more than one -- so
    the template just prints it verbatim; the actual "5.1"/"5.2" number in
    front of it comes from a real Word auto-number field (see
    scripts/build_report_template.py), not from anything in this class."""

    heading_text: str
    plain_paragraphs: list[str]
    list_paragraphs: list[str]


def _foundation_section_for(name: str, foundation_options: list[FoundationOption], *, heading_text: str) -> FoundationSection:
    option = find_foundation_option(name, foundation_options)
    if option is None:
        return FoundationSection(
            heading_text=heading_text,
            plain_paragraphs=[f'[No stored write-up for "{name}" -- add one to the foundation catalog.]'],
            list_paragraphs=[],
        )
    return FoundationSection(heading_text=heading_text, plain_paragraphs=option.plain_paragraphs, list_paragraphs=option.list_paragraphs)


def _foundation_context(project: Project, foundation_options: list[FoundationOption]) -> dict:
    """Section 5.1(+): one FoundationSection per name in
    recommended_foundations. A single recommendation keeps today's plain
    "Recommended Foundation: X" wording (case a); two or more each become
    "Option {n} - X" (case b), one subsection per name -- however many
    there are, since scripts/build_report_template.py loops this rather
    than hardcoding a fixed count."""
    names = [name.strip() for name in project.info.recommended_foundations if name.strip()]
    if not names:
        return {
            "foundation_sections": [
                FoundationSection(
                    heading_text="Recommended Foundation: [foundation type not specified]",
                    plain_paragraphs=["[No foundation was recommended on the input sheet -- fill in an Option field and regenerate.]"],
                    list_paragraphs=[],
                )
            ]
        }
    if len(names) == 1:
        return {"foundation_sections": [_foundation_section_for(names[0], foundation_options, heading_text=f"Recommended Foundation: {names[0]}")]}
    return {
        "foundation_sections": [
            _foundation_section_for(name, foundation_options, heading_text=f"Option {i + 1} - {name}") for i, name in enumerate(names)
        ]
    }


def build_report_context(
    project: Project,
    formation_templates: list[FormationTemplate],
    foundation_options: list[FoundationOption],
) -> dict:
    """Assemble the full docxtpl render context for `project`. Assumes the
    project's layers have already been hydrated with catalog descriptions
    (see catalog.hydrate_descriptions) -- this function only reads
    layer.description, it never looks the unit catalog up itself."""
    info = project.info
    num_pits = len(project.pits)
    primary_reason = _primary_termination_reason(project)

    context = {
        "report_date": _format_report_date(info.date, with_of=False),
        "report_date_numeric": _format_report_date_numeric(info.date),
        "project_number": info.project_number,
        "project_title_line": (
            f"GEOTECHNICAL REPORT, PROPOSED {info.project_name.upper()} – "
            f"{info.block_and_parcel.upper()}, {info.street_address.upper()}"
        ),
        "site_work_completion_date": _format_report_date(info.site_work_completion_date, with_of=True),
        "client": info.client,
        "engineer_name": info.engineer_name,
        "num_pits": num_pits,
        "num_pits_word": _number_word(num_pits),
        "pit_word": "pit" if num_pits == 1 else "pits",
        "equipment_lower": info.equipment.strip().lower(),
        "equipment_provider": info.equipment_provider,
        "proposed_structures": info.proposed_structures.strip().lower(),
        "pits": _build_pit_rows(project),
        "strata": _build_strata(project),
        "primary_formation": primary_reason.title(),
        "formation_commentary": _formation_commentary(project, primary_reason, formation_templates),
    }
    context.update(_notes_context(project))
    context.update(_foundation_context(project, foundation_options))
    return context


def render_docx_template(template_path: str | Path, context: dict, output_path: str | Path) -> None:
    """Renders any docxtpl template against a plain context dict and saves
    it -- shared by generate_report below and, in webapp/app.py, the
    header-only appendices (A/C/D), which need no context beyond
    build_report_context's own output.

    autoescape=True is not optional: docxtpl substitutes tag values by
    treating a document part's XML as a Jinja2 template string, so a raw
    "&" (or "<"/">") in any substituted value -- e.g. a project name like
    "Bryan & Jennifer Hunter Duplex" flowing into the header's
    project_title_line -- produces invalid XML that lxml then fails to
    re-parse (XMLSyntaxError: xmlParseEntityRef), crashing the render.
    autoescape=True makes Jinja2 escape those characters (to "&amp;" etc)
    the same way it would in HTML, which is exactly what well-formed XML
    also requires. docxtpl's own InlineImage/RichText/Subdoc objects
    (used elsewhere for photos) define __html__ specifically so Jinja2
    knows to insert their markup as-is instead of escaping it, so this is
    safe to enable unconditionally rather than only for reports that
    happen to need it."""
    tpl = DocxTemplate(template_path)
    tpl.render(context, autoescape=True)
    tpl.save(output_path)


def generate_report(
    project: Project,
    output_path: str | Path,
    formation_templates: list[FormationTemplate],
    foundation_options: list[FoundationOption],
    template_path: str | Path = DEFAULT_REPORT_TEMPLATE_PATH,
) -> None:
    """Render data/report_template.docx against `project` and save the
    result to `output_path`."""
    context = build_report_context(project, formation_templates, foundation_options)
    render_docx_template(template_path, context, output_path)
